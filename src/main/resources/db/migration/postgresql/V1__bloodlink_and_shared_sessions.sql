-- Cloud schema only. Local H2 continues to use Hibernate's student-friendly setup.
CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    username VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL CHECK (role IN ('DONOR', 'HOSPITAL'))
);

CREATE TABLE donor_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    full_name VARCHAR(80) NOT NULL,
    date_of_birth DATE NOT NULL,
    blood_group VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(120),
    city VARCHAR(80) NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    last_donation_date DATE,
    notifications_enabled BOOLEAN NOT NULL
);

CREATE TABLE hospital_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    name VARCHAR(100) NOT NULL,
    address VARCHAR(250) NOT NULL,
    city VARCHAR(80) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL
);

CREATE TABLE blood_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    hospital_id BIGINT NOT NULL REFERENCES hospital_profile(id),
    blood_group VARCHAR(255) NOT NULL,
    units_requested INTEGER NOT NULL CHECK (units_requested BETWEEN 1 AND 100),
    confirmed_units INTEGER NOT NULL CHECK (confirmed_units >= 0 AND confirmed_units <= units_requested),
    urgency VARCHAR(255) NOT NULL,
    required_by TIMESTAMP(6) NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE donor_response (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    request_id BIGINT NOT NULL REFERENCES blood_request(id),
    donor_id BIGINT NOT NULL REFERENCES donor_profile(id),
    status VARCHAR(255) NOT NULL,
    responded_at TIMESTAMP(6) NOT NULL,
    UNIQUE (request_id, donor_id)
);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    request_id BIGINT NOT NULL REFERENCES blood_request(id),
    donor_id BIGINT NOT NULL REFERENCES donor_profile(id),
    seen BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    UNIQUE (request_id, donor_id)
);

CREATE TABLE donation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    response_id BIGINT NOT NULL UNIQUE REFERENCES donor_response(id),
    units INTEGER NOT NULL CHECK (units > 0),
    confirmed_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE reward_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    donation_id BIGINT NOT NULL UNIQUE REFERENCES donation(id),
    points INTEGER NOT NULL CHECK (points = 100)
);

-- Spring Session JDBC's PostgreSQL schema, managed once by Flyway.
CREATE TABLE spring_session (
    primary_id CHAR(36) NOT NULL PRIMARY KEY,
    session_id CHAR(36) NOT NULL,
    creation_time BIGINT NOT NULL,
    last_access_time BIGINT NOT NULL,
    max_inactive_interval INTEGER NOT NULL,
    expiry_time BIGINT NOT NULL,
    principal_name VARCHAR(100)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session(session_id);
CREATE INDEX spring_session_ix2 ON spring_session(expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
    attribute_name VARCHAR(200) NOT NULL,
    attribute_bytes BYTEA NOT NULL,
    PRIMARY KEY (session_primary_id, attribute_name)
);
